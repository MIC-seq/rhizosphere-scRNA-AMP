#!/usr/bin/env python3
"""Create per-species raw-gene and COG-category sparse matrices for embedding."""
import argparse
import csv
import gzip
import re
from collections import Counter, defaultdict
from pathlib import Path


TARGETS = [
    "Chloracidobacterium validum",
    "Halomonas sp. JS92-SW72",
    "Pseudomonas aeruginosa",
]


def slug(value):
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", value)


def cog_codes(value):
    value = (value or "").strip()
    return sorted({char for char in value if char.isalpha() and char.isupper()})


def write_matrix(path, nrow, ncol, entries, field):
    with gzip.open(path, "wt", encoding="utf-8", newline="") as handle:
        handle.write(f"%%MatrixMarket matrix coordinate {field} general\n")
        handle.write("% generated by 23_prepare_species_function_matrices.py\n")
        handle.write(f"{nrow} {ncol} {len(entries)}\n")
        for row, col, value in entries:
            handle.write(f"{row} {col} {value}\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--bridge", required=True)
    parser.add_argument("--mapping-root", required=True)
    parser.add_argument("--annotation", required=True)
    parser.add_argument("--excluded", required=True)
    parser.add_argument("--outdir", required=True)
    args = parser.parse_args()
    out = Path(args.outdir); out.mkdir(parents=True, exist_ok=True)

    excluded = set()
    with open(args.excluded, encoding="utf-8") as handle:
        excluded = {row["gene_id"] for row in csv.DictReader(handle, delimiter="\t")}

    annotations, species_genes = {}, defaultdict(list)
    with open(args.annotation, encoding="utf-8") as handle:
        for row in csv.DictReader(handle, delimiter="\t"):
            if row["species"] not in TARGETS:
                continue
            text = (row.get("gene_biotype", "") + " " + row.get("product", "")).lower()
            if row["gene_id"] in excluded or "rrna" in text or "ribosomal rna" in text or "trna" in text or "transfer rna" in text:
                continue
            annotations[row["gene_id"]] = row
            species_genes[row["species"]].append(row["gene_id"])

    cells, sample_cells = defaultdict(list), defaultdict(dict)
    with gzip.open(args.bridge, "rt", encoding="utf-8") as handle:
        for row in csv.DictReader(handle, delimiter="\t"):
            species = row.get("gene_species", "")
            if species not in TARGETS or row.get("gene_qc_pass") != "1":
                continue
            cells[species].append(row)
            sample_cells[row["sample"]][row["cell_barcode"]] = (species, row["cell_id"])

    gene_counts, cog_counts = Counter(), Counter()
    for sample, barcode_map in sample_cells.items():
        path = Path(args.mapping_root) / sample / f"{sample}_gene_cell_counts.tsv.gz"
        with gzip.open(path, "rt", encoding="utf-8") as handle:
            for line in handle:
                gene, barcode, value = line.rstrip("\n").split("\t")
                target = barcode_map.get(barcode)
                annotation = annotations.get(gene)
                if not target or not annotation or annotation["species"] != target[0]:
                    continue
                count = int(value)
                species, cell_id = target
                gene_counts[(species, gene, cell_id)] += count
                codes = cog_codes(annotation.get("COG_category"))
                if codes:
                    share = count / len(codes)
                    for code in codes:
                        cog_counts[(species, code, cell_id)] += share

    summaries = []
    for species in TARGETS:
        directory = out / slug(species); directory.mkdir(exist_ok=True)
        cell_rows = sorted(cells[species], key=lambda row: row["cell_id"])
        cell_ids = [row["cell_id"] for row in cell_rows]
        cell_index = {cell: index + 1 for index, cell in enumerate(cell_ids)}
        observed_genes = sorted({gene for sp, gene, cell in gene_counts if sp == species})
        gene_index = {gene: index + 1 for index, gene in enumerate(observed_genes)}
        observed_cogs = sorted({code for sp, code, cell in cog_counts if sp == species})
        cog_index = {code: index + 1 for index, code in enumerate(observed_cogs)}
        gene_entries = sorted((gene_index[gene], cell_index[cell], value)
                              for (sp, gene, cell), value in gene_counts.items() if sp == species)
        cog_entries = sorted((cog_index[code], cell_index[cell], f"{value:.8g}")
                             for (sp, code, cell), value in cog_counts.items() if sp == species)
        write_matrix(directory / "gene_by_cell.mtx.gz", len(observed_genes), len(cell_ids), gene_entries, "integer")
        write_matrix(directory / "cog_by_cell.mtx.gz", len(observed_cogs), len(cell_ids), cog_entries, "real")
        with open(directory / "cells.tsv", "w", encoding="utf-8", newline="") as handle:
            fields = ["cell_id", "sample", "crop", "cell_barcode", "AMP_UMAP_1", "AMP_UMAP_2",
                      "AMP_cluster", "AMP_UMI_Fig4", "stable_AMP_count_Fig4", "gene_amp_load",
                      "gene_total_non_rrna_umi", "gene_detected_non_rrna_genes"]
            writer = csv.DictWriter(handle, fieldnames=fields, delimiter="\t", lineterminator="\n")
            writer.writeheader(); writer.writerows({field: row.get(field, "") for field in fields} for row in cell_rows)
        with open(directory / "genes.tsv", "w", encoding="utf-8", newline="") as handle:
            fields = ["gene_id", "locus_tag", "product", "COG_category", "COG_description", "eggNOG_ortholog"]
            writer = csv.DictWriter(handle, fieldnames=fields, delimiter="\t", lineterminator="\n")
            writer.writeheader(); writer.writerows({field: annotations[gene].get(field, "") for field in fields} for gene in observed_genes)
        with open(directory / "cogs.tsv", "w", encoding="utf-8", newline="") as handle:
            writer = csv.writer(handle, delimiter="\t", lineterminator="\n"); writer.writerow(["COG_category"])
            writer.writerows([[code] for code in observed_cogs])
        summaries.append({"species": species, "cells": len(cell_ids), "observed_genes": len(observed_genes),
                          "gene_matrix_nonzero": len(gene_entries), "observed_cog_categories": len(observed_cogs),
                          "cog_matrix_nonzero": len(cog_entries)})

    with open(out / "matrix_summary.tsv", "w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(summaries[0]), delimiter="\t", lineterminator="\n")
        writer.writeheader(); writer.writerows(summaries)
    print(summaries)


if __name__ == "__main__":
    main()
