suppressPackageStartupMessages(library(ape))
a <- read.tree('baseline199/tree/species_phylogeny.nwk')
b <- read.tree('supplemented207/tree/species_phylogeny.nwk')
norm <- function(x) sub('\\.(faa|fna)$','',x)
a$tip.label <- norm(a$tip.label); b$tip.label <- norm(b$tip.label)
shared <- intersect(a$tip.label,b$tip.label)
stopifnot(length(shared)>=4)
aa <- keep.tip(a,shared); bb <- keep.tip(b,shared)
rf <- as.numeric(dist.topo(unroot(aa),unroot(bb),method='PH85'))
da <- cophenetic.phylo(aa)[shared,shared];db <- cophenetic.phylo(bb)[shared,shared]
rho <- cor(da[upper.tri(da)],db[upper.tri(db)],method='spearman')
readtab <- function(branch) read.delim(file.path(branch,'source_data/plotted_species.tsv'))
ta <- readtab('baseline199');tb <- readtab('supplemented207')
result <- data.frame(metric=c('baseline_retained_tips','supplemented_retained_tips','shared_tips','baseline_abundance_percent','supplemented_abundance_percent','shared_tip_unrooted_RF','shared_tip_patristic_distance_spearman'),value=c(Ntip(a),Ntip(b),length(shared),sum(ta$pooled_percent),sum(tb$pooled_percent),rf,rho))
write.table(result,'source_data/tree_comparison.tsv',sep='\t',row.names=FALSE,quote=FALSE)
writeLines(c('Comparison restricted to shared tips; RF=0 indicates identical unrooted bipartitions.', 'Both analyses use the same protein prediction and marker workflow; changes reflect taxon-set effects and inference uncertainty.', 'The abundance denominator remains all pooled bacterial and archaeal transcript reads; not renormalized.', 'Outputs require visual and biological review before publication.'),'source_data/comparison_notes.txt')
print(result)
